"""Environment-driven configuration for the NavPro RMF fleet adapter."""

from __future__ import annotations

import os
from dataclasses import dataclass


def _env_bool(name: str, default: bool) -> bool:
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in ("1", "true", "yes", "on")


def _env_float(name: str, default: float) -> float:
    raw = os.environ.get(name)
    return float(raw) if raw else default


@dataclass(frozen=True)
class AdapterConfig:
    """All knobs, sourced from NAVPRO_* / PLATFORM_API_* env vars."""

    # RMF / fleet
    fleet_name: str
    fleet_config_path: str
    nav_graph_path: str
    server_uri: str | None
    use_sim_time: bool

    # zenoh
    zenoh_config_path: str | None

    # Platform API registry
    platform_api_url: str
    service_token: str | None
    provisioning_token: str | None
    poll_interval_sec: float

    # Optional state snapshots back to the platform
    post_state: bool
    state_post_interval_sec: float

    @classmethod
    def from_env(cls) -> "AdapterConfig":
        fleet_name = os.environ.get("NAVPRO_FLEET_NAME", "navpro")
        server_uri = os.environ.get("NAVPRO_SERVER_URI", "").strip() or None
        zenoh_config = os.environ.get("NAVPRO_ZENOH_CONFIG", "").strip() or None
        return cls(
            fleet_name=fleet_name,
            fleet_config_path=os.environ.get(
                "NAVPRO_FLEET_CONFIG", f"/site/fleet_config/{fleet_name}.yaml"
            ),
            nav_graph_path=os.environ.get(
                "NAVPRO_NAV_GRAPH", "/site/nav_graphs/0.yaml"
            ),
            server_uri=server_uri,
            use_sim_time=_env_bool("NAVPRO_USE_SIM_TIME", False),
            zenoh_config_path=zenoh_config,
            platform_api_url=os.environ.get(
                "PLATFORM_API_URL", "http://platform-api:3000"
            ).rstrip("/"),
            service_token=os.environ.get("PLATFORM_API_SERVICE_TOKEN") or None,
            provisioning_token=os.environ.get("PLATFORM_PROVISIONING_TOKEN")
            or None,
            poll_interval_sec=_env_float("NAVPRO_REGISTRY_POLL_INTERVAL", 5.0),
            post_state=_env_bool("NAVPRO_POST_ROBOT_STATE", False),
            state_post_interval_sec=_env_float(
                "NAVPRO_STATE_POST_INTERVAL", 2.0
            ),
        )

    def validate(self) -> None:
        if not os.path.isfile(self.fleet_config_path):
            raise FileNotFoundError(
                f"Fleet config not found: {self.fleet_config_path}. "
                "It is generated by the platform into /site/fleet_config/."
            )
        if not os.path.isfile(self.nav_graph_path):
            raise FileNotFoundError(
                f"Nav graph not found: {self.nav_graph_path}. "
                "It is generated by the platform into /site/nav_graphs/."
            )
        if self.service_token is None and self.provisioning_token is None:
            raise ValueError(
                "Registry auth missing: set PLATFORM_API_SERVICE_TOKEN "
                "(preferred) or PLATFORM_PROVISIONING_TOKEN."
            )
